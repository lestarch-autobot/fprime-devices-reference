"""L2-10: HD capture and preview download → four-quadrant 128×96 product tagged HD

Procedure (plan.json, verbatim order):
  MARK(2100)
  bracket (2 suncam samples)
  sunCamMgr.CAMERA_MODE_PRM_SET(HD)
  wait(ExposureReadback, 5 s)
  sunCamMgr.CAPTURE(SLOT_0, ON)
  wait(CaptureComplete, 20 s)
  sunCamMgr.DOWNLOAD(SLOT_0, PREVIEW, 0)
  wait(DownloadComplete, 60 s)
  sunCamMgr.CAMERA_MODE_PRM_SET(SD)
  wait(ExposureReadback, 5 s)
  sunCamMgr.CAPTURE(SLOT_0, OFF)
  wait(CaptureComplete, 10 s)
  sunCamMgr.CAPTURE(SLOT_1, OFF)
  wait(CaptureComplete, 10 s)
  sunCamMgr.CAPTURE(SLOT_2, OFF)
  wait(CaptureComplete, 10 s)
  sunCamMgr.CAPTURE(SLOT_3, OFF)
  wait(CaptureComplete, 10 s)
  bracket (2 suncam samples)
  MARK(2101)
"""
import pytest

from suncam import bracket, helper, wait_any


@pytest.mark.req('REQ-SunCamMgr-013', 'REQ-SunCamMgr-014', 'REQ-SunCamMgr-015', 'REQ-SunCamMgr-033')
def test_L2_10(fth_plan, window, check, require, send, bench):
    with window(2100, 2101):  # W
        require("STD")
        check('event sunCamMgr.SettingApplied(setting=CAMERA_MODE, value=3) count == 1')
        check('event sunCamMgr.SettingApplied(setting=CAMERA_MODE, value=1) count == 1')
        check('event sunCamMgr.SettingApplied(setting=EXPOSURE, value=672) count == 2')
        check('event sunCamMgr.ExposureReadback(pushed=672, readback=672) count == 2')
        check('event sunCamMgr.CaptureComplete(slot=SLOT_0, testPattern=ON, mode=HD) count == 1')
        check('event sunCamMgr.CaptureComplete(testPattern=OFF, exposure=672, mode=SD) count == 4')
        check('event sunCamMgr.DownloadStarted(slot=SLOT_0, imageMode=HD, resolution=PREVIEW, lines=192) count == 1')
        check('event sunCamMgr.DownloadComplete(slot=SLOT_0, imageMode=HD, resolution=PREVIEW, lines=192, bytes=12288) count == 1')
        check('event sunCamMgr.DownloadAborted count == 0')
        check('delta(sunCamMgr.LinesDownloaded) == 192')
        check('delta(sunCamMgr.ProductsSent) == 1')
        check('delta(sunCamMgr.ImagesCaptured) == 5')
        check('last(dpMgr.NumDataProducts) == 3')
        check('last(sunCamMgr.CameraMode) == SD')
        check('last(sunCamMgr.SetupState) == READY')
        check('one Image product in window: ImageHeader(slot=0, imageMode=HD, resolution=PREVIEW, width=128, height=96, exposure=672), 192 ImageLine records: slots 0, 1, 2, 3 in order, lines 0..47 each, placed TL/TR/BL/BR; PNG → dev-evidence/images/L2-10-hd-preview.png',
              helper(fth_plan, "decode_image_in_window", slot=0, image_mode='HD', resolution='PREVIEW', width=128, height=96, lines=192, expect='none', out='L2-10-hd-preview.png', exposure=672))
        check('event sunCamMgr.CameraError count == 0')
        check('event cmdDisp.OpCodeError count == 0')
        check('ABS')
        bracket(bench)
        send("sunCamMgr.CAMERA_MODE_PRM_SET", ['HD'])
        bench.wait_event("sunCamMgr.ExposureReadback", 5)
        send("sunCamMgr.CAPTURE", ['SLOT_0', 'ON'])
        bench.wait_event("sunCamMgr.CaptureComplete", 20)
        send("sunCamMgr.DOWNLOAD", ['SLOT_0', 'PREVIEW', '0'])
        bench.wait_event("sunCamMgr.DownloadComplete", 60)
        send("sunCamMgr.CAMERA_MODE_PRM_SET", ['SD'])
        bench.wait_event("sunCamMgr.ExposureReadback", 5)
        send("sunCamMgr.CAPTURE", ['SLOT_0', 'OFF'])
        bench.wait_event("sunCamMgr.CaptureComplete", 10)
        send("sunCamMgr.CAPTURE", ['SLOT_1', 'OFF'])
        bench.wait_event("sunCamMgr.CaptureComplete", 10)
        send("sunCamMgr.CAPTURE", ['SLOT_2', 'OFF'])
        bench.wait_event("sunCamMgr.CaptureComplete", 10)
        send("sunCamMgr.CAPTURE", ['SLOT_3', 'OFF'])
        bench.wait_event("sunCamMgr.CaptureComplete", 10)
        bracket(bench)
